/**
 * Builds src/data/state-outlines.ts: a simple outline (an SVG path) for each
 * state, drawn in the corner of the "It's About Time" cards.
 *
 * The borders come from U.S. Census Bureau boundary files (public domain),
 * packaged by the `us-atlas` npm package (ISC license).
 *
 * This is NOT part of the website build. Run it only when you want to add or
 * change a state, from the project folder:
 *
 *   npm install --no-save us-atlas topojson-client d3-geo
 *   node scripts/build-state-outlines.mjs MO IA LA TX NM AR
 *
 * List every state the site needs, using two-letter codes. Each outline is
 * shrunk to fit a 48 x 48 box, so a big state like Texas and a small one like
 * Iowa end up the same size.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoAlbers } from 'd3-geo';

const SIZE = 48; // the icon is drawn in a SIZE x SIZE box
const PAD = 3; // breathing room so the outline's stroke isn't clipped
const DETAIL = 0.35; // drops wiggles smaller than this (in px²); higher = simpler shape
const MIN_PIECE = 3; // drops islands smaller than this (in px²)

const NAMES = {
  AL: 'Alabama', AK: 'Alaska', AZ: 'Arizona', AR: 'Arkansas', CA: 'California', CO: 'Colorado',
  CT: 'Connecticut', DE: 'Delaware', FL: 'Florida', GA: 'Georgia', HI: 'Hawaii', ID: 'Idaho',
  IL: 'Illinois', IN: 'Indiana', IA: 'Iowa', KS: 'Kansas', KY: 'Kentucky', LA: 'Louisiana',
  ME: 'Maine', MD: 'Maryland', MA: 'Massachusetts', MI: 'Michigan', MN: 'Minnesota',
  MS: 'Mississippi', MO: 'Missouri', MT: 'Montana', NE: 'Nebraska', NV: 'Nevada',
  NH: 'New Hampshire', NJ: 'New Jersey', NM: 'New Mexico', NY: 'New York', NC: 'North Carolina',
  ND: 'North Dakota', OH: 'Ohio', OK: 'Oklahoma', OR: 'Oregon', PA: 'Pennsylvania',
  RI: 'Rhode Island', SC: 'South Carolina', SD: 'South Dakota', TN: 'Tennessee', TX: 'Texas',
  UT: 'Utah', VT: 'Vermont', VA: 'Virginia', WA: 'Washington', WV: 'West Virginia',
  WI: 'Wisconsin', WY: 'Wyoming',
};

const codes = process.argv.slice(2).map((code) => code.toUpperCase());
if (codes.length === 0 || codes.some((code) => !NAMES[code])) {
  console.error('Usage: node scripts/build-state-outlines.mjs MO IA LA TX NM AR');
  process.exit(1);
}

const topology = JSON.parse(readFileSync('node_modules/us-atlas/states-10m.json', 'utf8'));
const states = feature(topology, topology.objects.states).features;

/** Area of the triangle a-b-c. */
const triangle = (a, b, c) => Math.abs((b[0] - a[0]) * (c[1] - a[1]) - (c[0] - a[0]) * (b[1] - a[1])) / 2;

/** Area of a closed ring (shoelace formula). */
function ringArea(ring) {
  let sum = 0;
  for (let i = 0; i < ring.length; i++) {
    const [x1, y1] = ring[i];
    const [x2, y2] = ring[(i + 1) % ring.length];
    sum += x1 * y2 - x2 * y1;
  }
  return Math.abs(sum) / 2;
}

/** Visvalingam simplification: repeatedly drops the point that changes the shape least. */
function simplify(ring) {
  const points = ring.slice(0, -1); // the last point repeats the first
  while (points.length > 3) {
    let smallest = Infinity;
    let at = -1;
    for (let i = 0; i < points.length; i++) {
      const area = triangle(points[(i - 1 + points.length) % points.length], points[i], points[(i + 1) % points.length]);
      if (area < smallest) {
        smallest = area;
        at = i;
      }
    }
    if (smallest >= DETAIL) break;
    points.splice(at, 1);
  }
  return points;
}

const round = (n) => Math.round(n * 10) / 10;

function outline(code) {
  const state = states.find((s) => s.properties.name === NAMES[code]);
  // The same flat-map view used on a standard map of the U.S., so shapes look familiar.
  const projection = geoAlbers().fitExtent(
    [
      [PAD, PAD],
      [SIZE - PAD, SIZE - PAD],
    ],
    state,
  );
  const polygons = state.geometry.type === 'Polygon' ? [state.geometry.coordinates] : state.geometry.coordinates;
  const pieces = [];
  for (const polygon of polygons) {
    const ring = polygon[0].map((point) => projection(point)); // [0] = outer edge, ignoring holes
    if (ringArea(ring) < MIN_PIECE) continue;
    pieces.push(simplify(ring));
  }
  return pieces
    .map((points) => 'M' + points.map(([x, y]) => `${round(x)} ${round(y)}`).join('L') + 'Z')
    .join('');
}

const lines = codes.map((code) => {
  const d = outline(code);
  console.log(`${code}: ${d.length} characters`);
  return `  ${code}: '${d}',`;
});

writeFileSync(
  'src/data/state-outlines.ts',
  `/**
 * Simple state outlines (SVG paths) for the "It's About Time" cards.
 * GENERATED by scripts/build-state-outlines.mjs. Don't edit by hand; to add a
 * state, run that script again with every state code the site needs.
 * Borders: U.S. Census Bureau (public domain), via the us-atlas package (ISC).
 */

/** Each path is drawn in a OUTLINE_SIZE x OUTLINE_SIZE box. */
export const OUTLINE_SIZE = ${SIZE};

export const stateOutlines: Record<string, string> = {
${lines.join('\n')}
};
`,
);
console.log('Wrote src/data/state-outlines.ts');
